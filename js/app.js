const langMeta = {
    fr: { flag: '🇫🇷', code: 'FR' },
    en: { flag: '🇬🇧', code: 'EN' },
    es: { flag: '🇪🇸', code: 'ES' },
    de: { flag: '🇩🇪', code: 'DE' },
    pt: { flag: '🇧🇷', code: 'PT' }
};

let currentLang = 'fr';

function toggleLangMenu(e) {
    if (e) e.stopPropagation();
    const picker = document.getElementById('langPicker');
    const menu = document.getElementById('langMenu');
    const btn = document.getElementById('langPickerBtn');
    if (picker && menu) {
        const isOpen = picker.classList.toggle('open');
        menu.style.display = isOpen ? 'flex' : 'none';
        if (btn) btn.setAttribute('aria-expanded', isOpen ? 'true' : 'false');
    }
}

function selectLanguage(lang) {
    setLanguage(lang);
    const picker = document.getElementById('langPicker');
    const menu = document.getElementById('langMenu');
    const btn = document.getElementById('langPickerBtn');
    if (picker) picker.classList.remove('open');
    if (menu) menu.style.display = 'none';
    if (btn) btn.setAttribute('aria-expanded', 'false');
    try {
        localStorage.setItem('vox_lang', lang);
    } catch (_) {}
}

function setLanguage(lang) {
    if (!translations[lang]) lang = 'en';
    currentLang = lang;
    document.documentElement.lang = lang;

    const meta = langMeta[lang] || { flag: '🌐', code: lang.toUpperCase() };
    const flagEl = document.getElementById('currentFlag');
    const codeEl = document.getElementById('currentLangCode');
    if (flagEl) flagEl.textContent = meta.flag;
    if (codeEl) codeEl.textContent = meta.code;

    // Update active class in dropdown menu
    document.querySelectorAll('.lang-item').forEach(item => {
        item.classList.toggle('active', item.getAttribute('data-lang') === lang);
    });

    // Update document title and meta description for SEO & browser tab
    if (translations[lang]?.["page-title"]) {
        document.title = translations[lang]["page-title"];
    }
    const metaDesc = document.querySelector('meta[name="description"]');
    if (metaDesc && translations[lang]?.["page-desc"]) {
        metaDesc.setAttribute('content', translations[lang]["page-desc"]);
    }

    // Update i18n text in page
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        const val = translations[lang]?.[key];
        if (val !== undefined) el.innerHTML = val;
    });

    // Switch iPhone screenshots based on language (FR uses French, others use English universal screenshots)
    const isFr = lang === 'fr';
    const prompterImg = isFr ? 'assets/screenshot-prompter.png' : 'assets/screenshot-prompter_EN.PNG';
    const dashboard = document.getElementById('sc-dashboard');
    const prompter  = document.getElementById('sc-prompter');
    const hero      = document.getElementById('hero-img');
    const mirrorSc  = document.getElementById('sc-mirror');
    const mirrorDemo = document.getElementById('mirrorDemoImg');
    if (dashboard)  dashboard.src = isFr ? 'assets/screenshot-dashboard.png' : 'assets/screenshot-dashboard.png_EN.PNG';
    if (prompter)   prompter.src  = prompterImg;
    if (hero)       hero.src      = prompterImg;
    if (mirrorSc)   mirrorSc.src  = prompterImg;
    if (mirrorDemo) mirrorDemo.src = prompterImg;

    // Switch Apple Watch screenshots across all 5 localized versions (fr, en, es, de, pt)
    const watchLang = ['fr', 'en', 'es', 'de', 'pt'].includes(lang) ? lang : 'en';
    const watchSc1 = document.getElementById('watch-sc-1');
    const watchSc2 = document.getElementById('watch-sc-2');
    const watchSc3 = document.getElementById('watch-sc-3');
    if (watchSc1) watchSc1.src = `assets/watch/watch-01-${watchLang}.png`;
    if (watchSc2) watchSc2.src = `assets/watch/watch-02-${watchLang}.png`;
    if (watchSc3) watchSc3.src = `assets/watch/watch-03-${watchLang}.png`;

    // Refresh mirror demo status text for current language
    setMirrorMode(currentMirrorMode);
}

let currentMirrorMode = 'normal';

function setMirrorMode(mode) {
    currentMirrorMode = mode;
    const img = document.getElementById('mirrorDemoImg');
    const pillText = document.getElementById('mirrorStatusText');
    const buttons = document.querySelectorAll('.btn-mirror-toggle');

    buttons.forEach(btn => btn.classList.toggle('active', btn.getAttribute('data-mode') === mode));

    if (!img) return;

    if (mode === 'vertical') {
        img.style.transform = 'scale(1, -1)';
        if (pillText) pillText.textContent = translations[currentLang]?.["mirror-status-vertical"] || '🪞 Inversion Téléprompteur TV (Vitre à 45°)';
    } else if (mode === 'horizontal') {
        img.style.transform = 'scale(-1, 1)';
        if (pillText) pillText.textContent = translations[currentLang]?.["mirror-status-horizontal"] || '↔️ Inversion Gauche / Droite';
    } else {
        img.style.transform = 'scale(1, 1)';
        if (pillText) pillText.textContent = translations[currentLang]?.["mirror-status-normal"] || 'Mode Direct (Lecture iPhone)';
    }
}
window.setMirrorMode = setMirrorMode;

// Close language menu on outside click
window.addEventListener('click', (e) => {
    const picker = document.getElementById('langPicker');
    const menu = document.getElementById('langMenu');
    const btn = document.getElementById('langPickerBtn');
    if (picker && !picker.contains(e.target)) {
        picker.classList.remove('open');
        if (menu) menu.style.display = 'none';
        if (btn) btn.setAttribute('aria-expanded', 'false');
    }
});

// Scroll effect on navbar
window.addEventListener('scroll', () => {
    document.getElementById('navbar')?.classList.toggle('scrolled', window.scrollY > 20);
});

// Language detection on load: localStorage first, then navigator.languages
document.addEventListener('DOMContentLoaded', () => {
    let saved = null;
    try {
        saved = localStorage.getItem('vox_lang');
    } catch (_) {}

    if (saved && translations[saved]) {
        setLanguage(saved);
        return;
    }

    const preferred = navigator.languages ?? [navigator.language ?? 'fr'];
    for (const l of preferred) {
        const prefix = l.toLowerCase().split('-')[0];
        if (translations[prefix]) {
            setLanguage(prefix);
            break;
        }
    }
    if (!translations[currentLang]) {
        setLanguage('en');
    }

    // Attach click listeners to mirror buttons
    document.querySelectorAll('.btn-mirror-toggle').forEach(btn => {
        btn.addEventListener('click', (e) => {
            e.preventDefault();
            const mode = btn.getAttribute('data-mode');
            if (mode) setMirrorMode(mode);
        });
    });
});
